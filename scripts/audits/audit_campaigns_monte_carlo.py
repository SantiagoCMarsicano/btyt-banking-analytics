def simulate_worlds(
    production: pd.DataFrame,
    worlds: int,
    seed: int,
):
    n_campaigns = len(production)
    eligible = production["eligible_customers"].to_numpy(dtype=int)

    selection_mean = production["selection_rate_prod"].to_numpy(dtype=float)
    exposure_mean = production["exposure_rate_prod"].to_numpy(dtype=float)
    response_mean = production["response_rate_prod"].to_numpy(dtype=float)

    positive_share = production["positive_share_responders"].to_numpy(dtype=float)
    neutral_share = production["neutral_share_responders"].to_numpy(dtype=float)
    negative_share = production["negative_share_responders"].to_numpy(dtype=float)

    extra_events_mean = production["extra_events_per_exposed_prod"].to_numpy(
        dtype=float
    )

    rng_sel_p = make_rng(seed, RNG_STREAMS["selection_probability"])
    rng_sel = make_rng(seed, RNG_STREAMS["selection_realization"])
    rng_exp_p = make_rng(seed, RNG_STREAMS["exposure_probability"])
    rng_exp = make_rng(seed, RNG_STREAMS["exposure_realization"])
    rng_rsp_p = make_rng(seed, RNG_STREAMS["response_probability"])
    rng_rsp = make_rng(seed, RNG_STREAMS["response_realization"])
    rng_mix = make_rng(seed, RNG_STREAMS["response_mix"])
    rng_mix_real = make_rng(seed, RNG_STREAMS["response_mix_realization"])
    rng_follow_p = make_rng(seed, RNG_STREAMS["followup_intensity"])
    rng_follow = make_rng(seed, RNG_STREAMS["followup_realization"])

    selected = np.zeros((worlds, n_campaigns), dtype=np.int32)
    exposed = np.zeros((worlds, n_campaigns), dtype=np.int32)
    responding = np.zeros((worlds, n_campaigns), dtype=np.int32)
    positive = np.zeros((worlds, n_campaigns), dtype=np.int32)
    neutral = np.zeros((worlds, n_campaigns), dtype=np.int32)
    negative = np.zeros((worlds, n_campaigns), dtype=np.int32)
    exposure_events = np.zeros((worlds, n_campaigns), dtype=np.int32)

    for j in range(n_campaigns):
        a, b = beta_shapes(selection_mean[j], SELECTION_CONCENTRATION)
        p_sel = rng_sel_p.beta(a, b, size=worlds)
        selected[:, j] = rng_sel.binomial(eligible[j], p_sel)

        a, b = beta_shapes(exposure_mean[j], EXPOSURE_CONCENTRATION)
        p_exp = rng_exp_p.beta(a, b, size=worlds)
        exposed[:, j] = rng_exp.binomial(selected[:, j], p_exp)

        a, b = beta_shapes(response_mean[j], RESPONSE_CONCENTRATION)
        p_rsp = rng_rsp_p.beta(a, b, size=worlds)
        responding[:, j] = rng_rsp.binomial(exposed[:, j], p_rsp)

        # Response composition among responders. Add a weak symmetric prior so
        # small campaigns can produce categories not observed in one production
        # realization, while still remaining centered on the production mix.
        mix = np.array(
            [positive_share[j], neutral_share[j], negative_share[j]],
            dtype=float,
        )
        if mix.sum() <= 0:
            mix = np.array([0.50, 0.30, 0.20], dtype=float)
        mix = mix / mix.sum()

        alpha = 1.0 + RESPONSE_MIX_CONCENTRATION * mix
        world_mix = rng_mix.dirichlet(alpha, size=worlds)

        for w in range(worlds):
            n_resp = int(responding[w, j])
            if n_resp <= 0:
                continue
            draw = rng_mix_real.multinomial(n_resp, world_mix[w])
            positive[w, j] = int(draw[0])
            neutral[w, j] = int(draw[1])
            negative[w, j] = int(draw[2])

        # Extra successful contacts beyond the first exposure. Model the mean
        # extra-contact intensity with Gamma heterogeneity, then draw Poisson
        # extra events conditional on the number of exposed relationships.
        mean_extra = float(max(extra_events_mean[j], 0.0))
        if mean_extra <= EPS:
            exposure_events[:, j] = exposed[:, j]
        else:
            shape = FOLLOWUP_CONCENTRATION
            scale = mean_extra / FOLLOWUP_CONCENTRATION
            lambda_extra = rng_follow_p.gamma(shape, scale, size=worlds)
            extra = rng_follow.poisson(exposed[:, j] * lambda_extra)
            exposure_events[:, j] = exposed[:, j] + extra

    return {
        "selected": selected,
        "exposed": exposed,
        "responding": responding,
        "positive": positive,
        "neutral": neutral,
        "negative": negative,
        "exposure_events": exposure_events,
        "eligible": eligible,
    }


