def print_world_distribution(world_summary: pd.DataFrame) -> None:
    print("=" * 104)
    print("WORLD DISTRIBUTION SUMMARY")
    print("=" * 104)

    metrics = [
        ("overall_selection_rate", "Overall selection rate", True),
        ("overall_exposure_rate", "Overall exposure rate", True),
        ("overall_response_rate_exposed", "Response rate / exposed", True),
        ("events_per_exposed_relationship", "Exposure events / exposed", False),
        ("selected_relationships", "Selected relationships", False),
        ("exposed_relationships", "Exposed relationships", False),
        ("responding_relationships", "Observed responses", False),
    ]

    print(
        f"{'Metric':<31} {'Mean':>11} {'P05':>11} "
        f"{'Median':>11} {'P95':>11}"
    )

    for col, label, as_percent in metrics:
        arr = world_summary[col].to_numpy(dtype=float)
        vals = [
            float(arr.mean()),
            q(arr, 0.05),
            q(arr, 0.50),
            q(arr, 0.95),
        ]
        if as_percent:
            fmt = [pct(v) for v in vals]
        else:
            fmt = [f"{v:,.3f}" if "events" in col else f"{v:,.0f}" for v in vals]

        print(
            f"{label:<31} {fmt[0]:>11} {fmt[1]:>11} "
            f"{fmt[2]:>11} {fmt[3]:>11}"
        )
    print()


