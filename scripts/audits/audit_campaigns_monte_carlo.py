#!/usr/bin/env python
"""
BTYT Campaign Behavioral Layer — Monte Carlo Audit V1.0.0

Purpose
-------
Audit the distributional plausibility and stability of the frozen candidate
Campaign Behavioral Engine V1.0.2 without regenerating observable banking data.

This audit is deliberately lightweight. It does not rerun the full customer-level
campaign engine in every world. Instead it:

1. Reads the production Phase A outputs generated by V1.0.2.
2. Reconstructs campaign-level production counts and response composition.
3. Uses a hierarchical Beta-Binomial / Dirichlet-Multinomial Monte Carlo layer
   to stress selection, exposure, response, and response composition.
4. Preserves small-campaign uncertainty instead of forcing smooth percentages.
5. Audits production customer overlap, exposure concentration, fatigue proxies,
   and channel mix directly from the generated tables.
6. Applies broad structural/plausibility guardrails rather than target rates.

Important
---------
This is an audit of the realized campaign behavioral layer, not a replacement
generator and not a downstream conversion model.

No production table is modified.

Expected production inputs
--------------------------
data/generated/campaign_customers.csv
data/generated/campaign_exposures.csv
data/interim/campaign_generation_audit.csv
data/master/campaigns.csv
data/master/campaign_channels.csv

Outputs
-------
data/interim/campaign_monte_carlo_world_summary.csv
data/interim/campaign_monte_carlo_campaign_summary.csv
data/interim/campaign_monte_carlo_guardrails.csv
data/interim/campaign_production_behavior_diagnostics.csv
"""

