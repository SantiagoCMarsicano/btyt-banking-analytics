def parse_args():
    parser = argparse.ArgumentParser(
        description="BTYT Campaign Behavioral Layer Monte Carlo Audit V1.0.0"
    )
    parser.add_argument(
        "--worlds",
        type=int,
        default=DEFAULT_WORLDS,
        help=f"Monte Carlo worlds. Default: {DEFAULT_WORLDS:,}",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=DEFAULT_AUDIT_SEED,
        help=f"Audit seed. Default: {DEFAULT_AUDIT_SEED}",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()

    if args.worlds <= 0:
        raise ValueError("--worlds must be a positive integer.")

    campaigns, channels, campaign_customers, exposures, audit = load_inputs()
    production = add_production_rates(audit, exposures)

    print_header(args.worlds, args.seed, production)
    print("Running lightweight hierarchical Monte Carlo...")
    sim = simulate_worlds(production, args.worlds, args.seed)

    world_summary = build_world_summary(sim)
    campaign_summary = build_campaign_summary(production, sim)
    diagnostics = production_diagnostics(
        campaign_customers,
        exposures,
        channels,
    )
    guardrails = build_guardrails(
        production,
        world_summary,
        campaign_summary,
        diagnostics,
    )

    print_world_distribution(world_summary)
    print_campaign_distribution(campaign_summary)
    print_production_diagnostics(diagnostics)
    passed = print_guardrails(guardrails)

    save_outputs(
        world_summary,
        campaign_summary,
        guardrails,
        diagnostics,
    )

    print()
    print("=" * 104)
    print(
        f"BTYT CAMPAIGN MONTE CARLO AUDIT V{ENGINE_VERSION}: "
        f"{'PASS' if passed else 'FAIL'}"
    )
    print("=" * 104)
    print("No production campaign table was modified.")
    print("No downstream banking conversion was manufactured.")

    if not passed:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
