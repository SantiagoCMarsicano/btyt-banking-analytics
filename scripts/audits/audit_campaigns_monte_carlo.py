def make_rng(seed: int, stream: int) -> np.random.Generator:
    ss = np.random.SeedSequence([int(seed), int(stream)])
    return np.random.default_rng(ss)


def read_csv_required(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(f"Required file not found: {path}")
    df = pd.read_csv(path)
    unnamed = [c for c in df.columns if str(c).lower().startswith("unnamed")]
    if unnamed:
        df = df.drop(columns=unnamed)
    if "index" in df.columns:
        df = df.drop(columns=["index"])
    return df


def ensure_columns(df: pd.DataFrame, required: Iterable[str], name: str) -> None:
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(f"{name} is missing required columns: {missing}")


def pct(x: float) -> str:
    return f"{100.0 * x:6.2f}%"


def q(series: np.ndarray, p: float) -> float:
    return float(np.quantile(series, p))


def beta_shapes(mean: float, concentration: float) -> tuple[float, float]:
    mean = float(np.clip(mean, EPS, 1.0 - EPS))
    return mean * concentration, (1.0 - mean) * concentration


def safe_rate(num: np.ndarray, den: np.ndarray) -> np.ndarray:
    out = np.zeros_like(num, dtype=float)
    mask = den > 0
    out[mask] = num[mask] / den[mask]
    return out


def weighted_mean(values: np.ndarray, weights: np.ndarray) -> float:
    total = float(weights.sum())
    if total <= 0:
        return 0.0
    return float(np.sum(values * weights) / total)


