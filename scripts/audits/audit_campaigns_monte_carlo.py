def production_diagnostics(
    campaign_customers: pd.DataFrame,
    exposures: pd.DataFrame,
    channels: pd.DataFrame,
) -> pd.DataFrame:
    rows = []

    selected_per_customer = (
        campaign_customers.groupby("customer_id", observed=True)
        .size()
        .rename("campaign_selections")
    )

    exposed_pairs = campaign_customers[
        campaign_customers["exposure_status"].astype(str).str.upper() == "EXPOSED"
    ]
    exposed_per_customer = (
        exposed_pairs.groupby("customer_id", observed=True)
        .size()
        .rename("campaign_exposures")
    )

    event_per_customer = (
        exposures.groupby("customer_id", observed=True)
        .size()
        .rename("exposure_events")
    )

    for name, s in [
        ("campaign_selections_per_selected_customer", selected_per_customer),
        ("campaign_relationships_per_exposed_customer", exposed_per_customer),
        ("exposure_events_per_contacted_customer", event_per_customer),
    ]:
        values = s.to_numpy(dtype=float)
        rows.append(
            {
                "diagnostic": name,
                "n_customers": len(values),
                "mean": float(values.mean()) if len(values) else 0.0,
                "p50": q(values, 0.50) if len(values) else 0.0,
                "p95": q(values, 0.95) if len(values) else 0.0,
                "p99": q(values, 0.99) if len(values) else 0.0,
                "max": float(values.max()) if len(values) else 0.0,
                "share_ge_2": float(np.mean(values >= 2)) if len(values) else 0.0,
                "share_ge_3": float(np.mean(values >= 3)) if len(values) else 0.0,
                "share_ge_5": float(np.mean(values >= 5)) if len(values) else 0.0,
            }
        )

    # Channel mix diagnostics.
    if len(exposures):
        channel_counts = exposures["channel"].astype(str).str.upper().value_counts()
        total = int(channel_counts.sum())
        for channel, count in channel_counts.items():
            rows.append(
                {
                    "diagnostic": f"channel_share_{channel}",
                    "n_customers": np.nan,
                    "mean": count / total,
                    "p50": np.nan,
                    "p95": np.nan,
                    "p99": np.nan,
                    "max": np.nan,
                    "share_ge_2": np.nan,
                    "share_ge_3": np.nan,
                    "share_ge_5": np.nan,
                }
            )

    # Multi-channel relationships.
    if len(exposures):
        pair_channel_count = (
            exposures.groupby(["campaign_id", "customer_id"], observed=True)["channel"]
            .nunique()
        )
        rows.append(
            {
                "diagnostic": "channels_per_exposed_relationship",
                "n_customers": len(pair_channel_count),
                "mean": float(pair_channel_count.mean()),
                "p50": q(pair_channel_count.to_numpy(dtype=float), 0.50),
                "p95": q(pair_channel_count.to_numpy(dtype=float), 0.95),
                "p99": q(pair_channel_count.to_numpy(dtype=float), 0.99),
                "max": float(pair_channel_count.max()),
                "share_ge_2": float(np.mean(pair_channel_count >= 2)),
                "share_ge_3": float(np.mean(pair_channel_count >= 3)),
                "share_ge_5": float(np.mean(pair_channel_count >= 5)),
            }
        )

    # Authorized-channel coverage is a structural production diagnostic.
    authorized = set(
        zip(
            channels["campaign_id"].astype(str),
            channels["channel"].astype(str).str.upper(),
        )
    )
    actual = set(
        zip(
            exposures["campaign_id"].astype(str),
            exposures["channel"].astype(str).str.upper(),
        )
    )
    unauthorized = actual - authorized

    rows.append(
        {
            "diagnostic": "unauthorized_campaign_channel_pairs",
            "n_customers": np.nan,
            "mean": float(len(unauthorized)),
            "p50": np.nan,
            "p95": np.nan,
            "p99": np.nan,
            "max": np.nan,
            "share_ge_2": np.nan,
            "share_ge_3": np.nan,
            "share_ge_5": np.nan,
        }
    )

    return pd.DataFrame(rows)


