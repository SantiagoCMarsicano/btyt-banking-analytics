def build_world_summary(sim: dict) -> pd.DataFrame:
    selected = sim["selected"]
    exposed = sim["exposed"]
    responding = sim["responding"]
    positive = sim["positive"]
    neutral = sim["neutral"]
    negative = sim["negative"]
    exposure_events = sim["exposure_events"]
    eligible = sim["eligible"]

    worlds = selected.shape[0]

    total_eligible = np.full(worlds, eligible.sum(), dtype=float)
    total_selected = selected.sum(axis=1)
    total_exposed = exposed.sum(axis=1)
    total_responding = responding.sum(axis=1)
    total_positive = positive.sum(axis=1)
    total_neutral = neutral.sum(axis=1)
    total_negative = negative.sum(axis=1)
    total_events = exposure_events.sum(axis=1)

    return pd.DataFrame(
        {
            "world": np.arange(1, worlds + 1),
            "eligible_relationships": total_eligible.astype(int),
            "selected_relationships": total_selected,
            "exposed_relationships": total_exposed,
            "responding_relationships": total_responding,
            "positive_responses": total_positive,
            "neutral_responses": total_neutral,
            "negative_responses": total_negative,
            "exposure_events": total_events,
            "overall_selection_rate": safe_rate(total_selected, total_eligible),
            "overall_exposure_rate": safe_rate(total_exposed, total_selected),
            "overall_response_rate_exposed": safe_rate(
                total_responding, total_exposed
            ),
            "events_per_exposed_relationship": safe_rate(
                total_events, total_exposed
            ),
        }
    )


def build_campaign_summary(
    production: pd.DataFrame,
    sim: dict,
) -> pd.DataFrame:
    rows = []

    for j, row in production.reset_index(drop=True).iterrows():
        selected = sim["selected"][:, j]
        exposed = sim["exposed"][:, j]
        responding = sim["responding"][:, j]
        positive = sim["positive"][:, j]
        neutral = sim["neutral"][:, j]
        negative = sim["negative"][:, j]
        events = sim["exposure_events"][:, j]

        eligible = np.full_like(selected, int(row["eligible_customers"]))

        selection_rate = safe_rate(selected, eligible)
        exposure_rate = safe_rate(exposed, selected)
        response_rate = safe_rate(responding, exposed)
        events_per_exposed = safe_rate(events, exposed)

        rows.append(
            {
                "campaign_id": row["campaign_id"],
                "campaign_name": row["campaign_name"],
                "campaign_type": row["campaign_type"],
                "eligible_customers": int(row["eligible_customers"]),
                "production_selection_rate": row["selection_rate_prod"],
                "selection_mean": float(selection_rate.mean()),
                "selection_p05": q(selection_rate, 0.05),
                "selection_p50": q(selection_rate, 0.50),
                "selection_p95": q(selection_rate, 0.95),
                "production_exposure_rate": row["exposure_rate_prod"],
                "exposure_mean": float(exposure_rate.mean()),
                "exposure_p05": q(exposure_rate, 0.05),
                "exposure_p50": q(exposure_rate, 0.50),
                "exposure_p95": q(exposure_rate, 0.95),
                "production_response_rate": row["response_rate_prod"],
                "response_mean": float(response_rate.mean()),
                "response_p05": q(response_rate, 0.05),
                "response_p50": q(response_rate, 0.50),
                "response_p95": q(response_rate, 0.95),
                "production_events_per_exposed": row["events_per_exposed_prod"],
                "events_per_exposed_mean": float(events_per_exposed.mean()),
                "events_per_exposed_p05": q(events_per_exposed, 0.05),
                "events_per_exposed_p50": q(events_per_exposed, 0.50),
                "events_per_exposed_p95": q(events_per_exposed, 0.95),
                "zero_selected_world_share": float(np.mean(selected == 0)),
                "zero_exposed_world_share": float(np.mean(exposed == 0)),
                "zero_response_world_share": float(np.mean(responding == 0)),
                "all_selected_exposed_world_share": float(
                    np.mean((selected > 0) & (exposed == selected))
                ),
                "positive_mean": float(positive.mean()),
                "neutral_mean": float(neutral.mean()),
                "negative_mean": float(negative.mean()),
            }
        )

    return pd.DataFrame(rows)


