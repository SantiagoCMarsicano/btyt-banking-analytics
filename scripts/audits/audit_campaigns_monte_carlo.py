def build_guardrails(
    production: pd.DataFrame,
    world_summary: pd.DataFrame,
    campaign_summary: pd.DataFrame,
    diagnostics: pd.DataFrame,
) -> pd.DataFrame:
    checks = []

    def add(name: str, passed: bool, observed, rule: str):
        checks.append(
            {
                "check": name,
                "status": "PASS" if passed else "FAIL",
                "observed": observed,
                "rule": rule,
            }
        )

    exp = world_summary["overall_exposure_rate"].to_numpy()
    rsp = world_summary["overall_response_rate_exposed"].to_numpy()
    evp = world_summary["events_per_exposed_relationship"].to_numpy()
    sel = world_summary["overall_selection_rate"].to_numpy()

    # Broad model-level guardrails. These are not calibration targets.
    add(
        "overall_selection_distribution_plausible",
        q(sel, 0.05) > 0.05 and q(sel, 0.95) < 0.65,
        f"P05={pct(q(sel, 0.05))}, P95={pct(q(sel, 0.95))}",
        "P05 > 5% and P95 < 65%",
    )
    add(
        "overall_exposure_distribution_plausible",
        q(exp, 0.05) > 0.60 and q(exp, 0.95) < 0.97,
        f"P05={pct(q(exp, 0.05))}, P95={pct(q(exp, 0.95))}",
        "P05 > 60% and P95 < 97%",
    )
    add(
        "overall_response_distribution_plausible",
        q(rsp, 0.05) > 0.03 and q(rsp, 0.95) < 0.40,
        f"P05={pct(q(rsp, 0.05))}, P95={pct(q(rsp, 0.95))}",
        "P05 > 3% and P95 < 40%",
    )
    add(
        "contact_frequency_plausible",
        q(evp, 0.05) >= 1.0 and q(evp, 0.95) < 3.5,
        f"P05={q(evp, 0.05):.3f}, P95={q(evp, 0.95):.3f}",
        "P05 >= 1.0 and P95 < 3.5 exposure events per exposed relationship",
    )

    # Large campaigns should not frequently disappear entirely.
    large = campaign_summary[campaign_summary["eligible_customers"] >= 500]
    add(
        "large_campaigns_rarely_zero_selection",
        bool((large["zero_selected_world_share"] < 0.01).all()),
        f"max zero-selected share={large['zero_selected_world_share'].max():.4f}",
        "Eligible >= 500: zero-selected world share < 1%",
    )
    add(
        "large_campaigns_rarely_zero_exposure",
        bool((large["zero_exposed_world_share"] < 0.01).all()),
        f"max zero-exposed share={large['zero_exposed_world_share'].max():.4f}",
        "Eligible >= 500: zero-exposed world share < 1%",
    )

    # Small campaigns are allowed to be noisy. We explicitly require that at
    # least one small campaign has meaningful zero-response probability, which
    # protects against accidental deterministic smoothing.
    small = campaign_summary[campaign_summary["eligible_customers"] < 100]
    if len(small):
        max_zero_resp = float(small["zero_response_world_share"].max())
        add(
            "small_campaign_volatility_preserved",
            max_zero_resp >= 0.05,
            f"max zero-response world share={max_zero_resp:.4f}",
            "At least one eligible<100 campaign has >=5% zero-response worlds",
        )
    else:
        add(
            "small_campaign_volatility_preserved",
            True,
            "No eligible<100 campaigns in production",
            "Not applicable",
        )

    # Exposure must not collapse back to the V1.0.1 near-certainty regime.
    large_exp_p95 = float(
        campaign_summary.loc[
            campaign_summary["eligible_customers"] >= 500,
            "exposure_p95",
        ].median()
    )
    add(
        "delivery_not_near_deterministic",
        large_exp_p95 < 0.97,
        f"median large-campaign exposure P95={pct(large_exp_p95)}",
        "Median large-campaign exposure P95 < 97%",
    )

    # Production overlap / concentration.
    diag_map = diagnostics.set_index("diagnostic")["mean"].to_dict()
    unauthorized = float(diag_map.get("unauthorized_campaign_channel_pairs", 0.0))
    add(
        "authorized_channels_only",
        unauthorized == 0.0,
        f"unauthorized pairs={int(unauthorized)}",
        "No actual campaign/channel pair may be unauthorized",
    )

    exposure_customer_diag = diagnostics[
        diagnostics["diagnostic"] == "exposure_events_per_contacted_customer"
    ]
    if len(exposure_customer_diag):
        p99 = float(exposure_customer_diag.iloc[0]["p99"])
        max_events = float(exposure_customer_diag.iloc[0]["max"])
        add(
            "customer_contact_concentration_plausible",
            p99 < 12 and max_events < 25,
            f"P99={p99:.1f}, max={max_events:.0f}",
            "P99 < 12 and max < 25 exposure events per contacted customer",
        )

    multi_diag = diagnostics[
        diagnostics["diagnostic"] == "channels_per_exposed_relationship"
    ]
    if len(multi_diag):
        share_multi = float(multi_diag.iloc[0]["share_ge_2"])
        add(
            "multichannel_not_universal",
            share_multi < 0.75,
            f"share with >=2 channels={pct(share_multi)}",
            "Less than 75% of exposed relationships use multiple channels",
        )

    # Structural production consistency from aggregate counts.
    count_identity = bool(
        (
            production["positive_responses"]
            + production["neutral_responses"]
            + production["negative_responses"]
            == production["responding_customers"]
        ).all()
    )
    add(
        "response_composition_reconciles",
        count_identity,
        "campaign-level response categories checked",
        "Positive + neutral + negative = responding customers",
    )

    return pd.DataFrame(checks)


