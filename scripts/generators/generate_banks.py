def validate_banks(banks_df: pd.DataFrame) -> None:
    if banks_df["bank_id"].duplicated().any():
        raise ValueError("Duplicate bank_id detected.")

    if banks_df["bank_name"].duplicated().any():
        raise ValueError("Duplicate current-state bank_name detected.")

    allowed_scopes = {"BTYT", "DOMESTIC", "FOREIGN"}

    if not set(banks_df["bank_scope"]).issubset(allowed_scopes):
        raise ValueError("Invalid bank_scope detected.")

    affinity_columns = [
        "usd_affinity",
        "business_affinity",
        "large_transfer_affinity",
    ]

    for column in affinity_columns:
        if not banks_df[column].between(0.0, 1.0).all():
            raise ValueError(f"{column} must be between 0 and 1.")

    b010 = banks_df.loc[banks_df["bank_id"] == "B010"]

    if len(b010) != 1:
        raise ValueError("B010 must exist exactly once.")

    if b010.iloc[0]["bank_name"] != "BTG Pactual Uruguay":
        raise ValueError(
            "B010 current-state name must be BTG Pactual Uruguay."
        )

    missing_market_configs = (
        set(DOMESTIC_SYSTEM_IDS)
        - set(INITIAL_MARKET_SPECS)
    )

    if missing_market_configs:
        raise ValueError(
            f"Missing initial market specs: {sorted(missing_market_configs)}"
        )

    missing_dynamic_configs = (
        set(DOMESTIC_SYSTEM_IDS)
        - set(MARKET_DYNAMICS)
    )

    if missing_dynamic_configs:
        raise ValueError(
            f"Missing market dynamics: {sorted(missing_dynamic_configs)}"
        )


def validate_world_parameters(
    banks_df: pd.DataFrame,
    world_df: pd.DataFrame,
) -> None:
    if world_df["bank_id"].duplicated().any():
        raise ValueError("Duplicate bank_id in bank_world_parameters.csv.")

    expected_ids = set(banks_df["bank_id"])

    if set(world_df["bank_id"]) != expected_ids:
        raise ValueError(
            "World-parameter bank IDs do not match banks.csv."
        )

    expected_names = banks_df.set_index("bank_id")["bank_name"].to_dict()

    mismatched_names = world_df[
        world_df.apply(
            lambda row: expected_names[row["bank_id"]] != row["bank_name"],
            axis=1,
        )
    ]

    if not mismatched_names.empty:
        raise ValueError(
            "bank_name does not match bank_id in world parameters."
        )

    affinity_columns = [
        "realized_usd_affinity",
        "realized_business_affinity",
        "realized_large_transfer_affinity",
    ]

    for column in affinity_columns:
        if not world_df[column].between(0.0, 1.0).all():
            raise ValueError(f"{column} must be between 0 and 1.")

    merged = world_df.merge(
        banks_df[["bank_id", "bank_scope"]],
        on="bank_id",
        how="left",
        validate="one_to_one",
    )

    foreign = merged.loc[merged["bank_scope"] == "FOREIGN"].copy()
    non_foreign = merged.loc[merged["bank_scope"] != "FOREIGN"].copy()

    if not np.isclose(
        foreign["foreign_selection_weight"].sum(),
        1.0,
        atol=1e-10,
    ):
        raise ValueError("Foreign selection weights do not sum to 1.")

    if (foreign["foreign_selection_weight"] <= 0).any():
        raise ValueError("Foreign selection weights must be positive.")

    if non_foreign["foreign_selection_weight"].notna().any():
        raise ValueError(
            "Only foreign banks may have foreign_selection_weight."
        )

    domestic_system = world_df.loc[
        world_df["bank_id"].isin(DOMESTIC_SYSTEM_IDS)
    ]

    if domestic_system["market_persistence"].isna().any():
        raise ValueError(
            "Domestic-system banks require market_persistence."
        )

    if not domestic_system["market_persistence"].between(
        0.0,
        1.0,
        inclusive="neither",
    ).all():
        raise ValueError("Market persistence must lie inside (0,1).")

    if (domestic_system["market_innovation_sd"] <= 0).any():
        raise ValueError("Market innovation SD must be positive.")



def validate_market_weights(
    banks_df: pd.DataFrame,
    market_df: pd.DataFrame,
) -> None:
    expected_rows = len(DOMESTIC_SYSTEM_IDS) * len(YEARS)

    if len(market_df) != expected_rows:
        raise ValueError(
            f"Expected {expected_rows} market rows, found {len(market_df)}."
        )

    if market_df.duplicated(["bank_id", "year"]).any():
        raise ValueError("Duplicate (bank_id, year) in market weights.")

    if set(market_df["bank_id"]) != set(DOMESTIC_SYSTEM_IDS):
        raise ValueError("Unexpected bank IDs in domestic market table.")

    if set(market_df["year"]) != set(YEARS):
        raise ValueError("Domestic market table has incorrect year coverage.")

    if (market_df["market_weight"] <= 0).any():
        raise ValueError("Domestic market weights must be positive.")

    annual_sums = market_df.groupby("year")["market_weight"].sum()

    if not np.allclose(
        annual_sums.to_numpy(),
        np.ones(len(annual_sums)),
        atol=1e-10,
    ):
        raise ValueError("Annual domestic market weights do not sum to 1.")

    annual_max = market_df.groupby("year")["market_weight"].max()

    if (annual_max > MAX_DOMESTIC_WEIGHT_GUARDRAIL).any():
        raise ValueError(
            "A domestic market weight exceeded the configured guardrail."
        )

    current_names = get_bank_lookup(banks_df)

    mismatched_names = market_df[
        market_df.apply(
            lambda row: get_temporal_bank_name(
                row["bank_id"],
                int(row["year"]),
                current_names[row["bank_id"]],
            )
            != row["bank_name"],
            axis=1,
        )
    ]

    if not mismatched_names.empty:
        raise ValueError(
            "Temporal bank_name mismatch in market weights."
        )

    initial = (
        market_df.loc[market_df["year"] == 2021]
        .set_index("bank_id")
    )

    for bank_id in DOMESTIC_SYSTEM_IDS:
        value = float(initial.loc[bank_id, "market_weight"])
        low = INITIAL_MARKET_SPECS[bank_id]["low"]
        high = INITIAL_MARKET_SPECS[bank_id]["high"]

        if value < low - 1e-10 or value > high + 1e-10:
            raise ValueError(
                f"2021 weight for {bank_id} falls outside its band."
            )

    leader_2021 = initial["market_weight"].idxmax()

    if leader_2021 != "B001":
        raise ValueError("BROU must be the 2021 market leader.")

    btyt_2021 = float(initial.loc["B000", "market_weight"])

    if not (
        INITIAL_MARKET_SPECS["B000"]["low"]
        <= btyt_2021
        <= INITIAL_MARKET_SPECS["B000"]["high"]
    ):
        raise ValueError("BTYT 2021 weight is outside its design band.")

    if not market_df["persistence"].between(
        0.0,
        1.0,
        inclusive="neither",
    ).all():
        raise ValueError("Invalid persistence in market table.")

    if market_df[
        [
            "latent_competitive_state",
            "long_run_anchor",
            "macro_effect",
            "systemic_shock_effect",
            "bank_shock_effect",
            "persistent_strategic_effect",
            "idiosyncratic_innovation",
        ]
    ].isna().any().any():
        raise ValueError("Missing market-dynamics components detected.")

    shock_consistency = (
        market_df["is_bank_shock"]
        == (market_df["bank_shock_effect"] != 0.0)
    )

    if not shock_consistency.all():
        raise ValueError("Bank-shock flag/value mismatch.")


def validate_financials(
    banks_df: pd.DataFrame,
    financials_df: pd.DataFrame,
) -> None:
    if financials_df.duplicated(["bank_id", "year"]).any():
        raise ValueError("Duplicate (bank_id, year) in bank financials.")

    known_ids = set(banks_df["bank_id"])

    if set(financials_df["bank_id"]) != known_ids:
        raise ValueError(
            "Financial bank IDs do not match banks.csv."
        )

    expected_rows = len(banks_df) * len(YEARS)

    if len(financials_df) != expected_rows:
        raise ValueError(
            f"Expected {expected_rows} financial rows, "
            f"found {len(financials_df)}."
        )

    coverage = financials_df.groupby("bank_id")["year"].apply(set)

    if not all(years == set(YEARS) for years in coverage):
        raise ValueError("Incomplete financial year coverage.")

    current_names = get_bank_lookup(banks_df)

    mismatched_names = financials_df[
        financials_df.apply(
            lambda row: get_temporal_bank_name(
                row["bank_id"],
                int(row["year"]),
                current_names[row["bank_id"]],
            )
            != row["bank_name"],
            axis=1,
        )
    ]

    if not mismatched_names.empty:
        raise ValueError(
            "Temporal bank_name mismatch in financials."
        )

    positive_columns = [
        "revenue",
        "operating_costs",
        "total_assets",
        "total_deposits",
        "total_loans",
        "equity",
    ]

    for column in positive_columns:
        if (financials_df[column] <= 0).any():
            raise ValueError(f"{column} must be positive.")

    if (
        financials_df["total_loans"]
        >= financials_df["total_assets"]
    ).any():
        raise ValueError("total_loans must remain below total_assets.")

    if (
        financials_df["total_deposits"]
        >= financials_df["total_assets"]
    ).any():
        raise ValueError("total_deposits must remain below total_assets.")

    if (
        financials_df["equity"]
        >= financials_df["total_assets"]
    ).any():
        raise ValueError("equity must remain below total_assets.")

    if financials_df["net_income"].isna().any():
        raise ValueError("Missing net_income detected.")

    if set(financials_df["reporting_currency"]) != {REPORTING_CURRENCY}:
        raise ValueError("Unexpected reporting currency.")


