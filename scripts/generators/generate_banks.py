# =============================================================================
# BTYT BANKING ANALYTICS — BANK NETWORK GENERATOR V4.0.1
# =============================================================================
#
# Generates:
#   1. banks.csv
#   2. bank_world_parameters.csv
#   3. bank_market_weights.csv
#   4. bank_financials.csv
#
# Consumes:
#   - data/generated/world/macro_environment.csv
#
# Optional:
#   6. bank_market_weights_audit.csv
#
# V4.0.1 calibration:
#   - Preserves the V4.0.0 architecture and 2021 initialization contract.
#   - Raises competitive-state persistence to reduce excessive mean reversion.
#   - Adds persistent strategic-shock carryover with gradual decay.
#   - Keeps ordinary annual noise moderate.
#   - Gives BROU a rare severe strategic-shock channel so leadership changes
#     are possible without making them common.
#
# V4.0.0 redesign:
#   - BTYT enters the synthetic domestic competitive system.
#   - The 2021 domestic state is generated from bounded plausibility bands.
#   - BROU is required to start as the largest domestic-system institution.
#   - Domestic competitive weights evolve annually from 2021 through 2026.
#   - Market dynamics use persistent mean-reverting latent AR-style states.
#   - Annual weights are obtained with a softmax transformation.
#   - Macro factors, systemic shocks, bank-specific shocks, and ordinary
#     idiosyncratic innovations affect competitive trajectories.
#   - BTYT has no protected growth path and may gain or lose.
#   - Domestic financial trajectories are partially linked to competitive
#     dynamics and the shared macro environment.
#   - B010 keeps one stable bank_id while its temporal display name changes:
#       2021-2025 -> HSBC Uruguay
#       2026      -> BTG Pactual Uruguay
#   - Independent deterministic RNG streams preserve modular reproducibility.
#
# All data generated by this script are synthetic.
# All code and comments are intentionally written in English.
# =============================================================================


