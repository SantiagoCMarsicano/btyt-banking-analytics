def generate_production_world(
    world_seed: int,
    save: bool = True,
) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    banks_df = build_banks_dataframe()
    validate_banks(banks_df)

    world_df = build_world_parameters_dataframe(
        banks_df=banks_df,
        world_seed=world_seed,
    )
    validate_world_parameters(banks_df, world_df)

    macro_df = load_macro_environment(
        expected_world_seed=world_seed,
    )

    market_df = build_market_weights_dataframe(
        banks_df=banks_df,
        world_params_df=world_df,
        macro_df=macro_df,
        world_seed=world_seed,
    )
    validate_market_weights(
        banks_df=banks_df,
        market_df=market_df,
    )

    financials_df = build_bank_financials_dataframe(
        macro_df=macro_df,
        market_df=market_df,
        world_seed=world_seed,
    )
    validate_financials(
        banks_df=banks_df,
        financials_df=financials_df,
    )

    if save:
        BANKS_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        WORLD_PARAMS_OUTPUT.parent.mkdir(parents=True, exist_ok=True)

        banks_df.to_csv(BANKS_OUTPUT, index=False)
        world_df.to_csv(WORLD_PARAMS_OUTPUT, index=False)
        market_df.to_csv(MARKET_OUTPUT, index=False)
        financials_df.to_csv(FINANCIALS_OUTPUT, index=False)

    return (
        banks_df,
        world_df,
        macro_df,
        market_df,
        financials_df,
    )


