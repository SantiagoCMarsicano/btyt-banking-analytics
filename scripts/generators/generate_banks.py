def run_market_audit(
    banks_df: pd.DataFrame,
    n_worlds: int,
    audit_seed: int,
) -> pd.DataFrame:
    """
    Audit only the competitive engine.

    Financial generation is deliberately excluded so a 10,000-world audit can
    remain lightweight enough for development use.
    """
    if n_worlds <= 0:
        raise ValueError("n_worlds must be positive.")

    names = get_bank_lookup(banks_df)

    records = []
    leader_change_count = 0
    btyt_gain_count = 0
    systemic_year_count = 0
    bank_shock_count = 0

    for world_index in range(n_worlds):
        world_seed = int(audit_seed + world_index)

        world_df = build_world_parameters_dataframe(
            banks_df,
            world_seed,
        )
        macro_df = build_macro_environment_dataframe(world_seed)
        market_df = build_market_weights_dataframe(
            banks_df=banks_df,
            world_params_df=world_df,
            macro_df=macro_df,
            world_seed=world_seed,
        )

        weights_2021 = (
            market_df.loc[market_df["year"] == 2021]
            .set_index("bank_id")["market_weight"]
        )
        weights_2026 = (
            market_df.loc[market_df["year"] == 2026]
            .set_index("bank_id")["market_weight"]
        )

        ranks_2021 = weights_2021.rank(
            ascending=False,
            method="min",
        )
        ranks_2026 = weights_2026.rank(
            ascending=False,
            method="min",
        )

        leader_2021 = weights_2021.idxmax()
        leader_2026 = weights_2026.idxmax()

        if leader_2021 != leader_2026:
            leader_change_count += 1

        if weights_2026["B000"] > weights_2021["B000"]:
            btyt_gain_count += 1

        systemic_year_count += int(
            macro_df["systemic_shock_flag"].sum()
        )
        bank_shock_count += int(
            market_df["is_bank_shock"].sum()
        )

        for bank_id in DOMESTIC_SYSTEM_IDS:
            records.append(
                {
                    "world_seed": world_seed,
                    "bank_id": bank_id,
                    "weight_2021": float(weights_2021[bank_id]),
                    "weight_2026": float(weights_2026[bank_id]),
                    "change_2021_2026": float(
                        weights_2026[bank_id]
                        - weights_2021[bank_id]
                    ),
                    "rank_2021": int(ranks_2021[bank_id]),
                    "rank_2026": int(ranks_2026[bank_id]),
                    "leader_2021": bank_id == leader_2021,
                    "leader_2026": bank_id == leader_2026,
                    "top3_2021": ranks_2021[bank_id] <= 3,
                    "top3_2026": ranks_2026[bank_id] <= 3,
                }
            )

    detail = pd.DataFrame(records)

    rows = []

    for bank_id in DOMESTIC_SYSTEM_IDS:
        bank = detail.loc[detail["bank_id"] == bank_id]

        rows.append(
            {
                "bank_id": bank_id,
                "bank_name": names[bank_id],
                "mean_2021": bank["weight_2021"].mean(),
                "median_2021": bank["weight_2021"].median(),
                "p05_2021": bank["weight_2021"].quantile(0.05),
                "p95_2021": bank["weight_2021"].quantile(0.95),
                "leader_pct_2021": bank["leader_2021"].mean(),
                "top3_pct_2021": bank["top3_2021"].mean(),
                "mean_2026": bank["weight_2026"].mean(),
                "median_2026": bank["weight_2026"].median(),
                "p05_2026": bank["weight_2026"].quantile(0.05),
                "p95_2026": bank["weight_2026"].quantile(0.95),
                "leader_pct_2026": bank["leader_2026"].mean(),
                "top3_pct_2026": bank["top3_2026"].mean(),
                "mean_change_2021_2026": bank[
                    "change_2021_2026"
                ].mean(),
                "gain_pct_2021_2026": (
                    bank["change_2021_2026"] > 0
                ).mean(),
            }
        )

    summary = pd.DataFrame(rows).sort_values(
        "mean_2021",
        ascending=False,
    )

    print("\n" + "=" * 92)
    print("BTYT V4 DOMESTIC MARKET AUDIT")
    print("=" * 92)
    print(f"Worlds simulated: {n_worlds:,}")
    print(f"Audit seed: {audit_seed}")
    print(f"2021 market RNG stream: {RNG_STREAM_2021_MARKET}")
    print(f"Market dynamics RNG stream: {RNG_STREAM_MARKET_DYNAMICS}")
    print()

    print(
        f"{'Bank':<28}"
        f"{'2021 Mean':>11}"
        f"{'2021 P05':>10}"
        f"{'2021 P95':>10}"
        f"{'2026 Mean':>11}"
        f"{'2026 P05':>10}"
        f"{'2026 P95':>10}"
        f"{'Gain %':>9}"
    )

    for row in summary.itertuples(index=False):
        print(
            f"{row.bank_name:<28}"
            f"{row.mean_2021:>10.2%}"
            f"{row.p05_2021:>10.2%}"
            f"{row.p95_2021:>10.2%}"
            f"{row.mean_2026:>11.2%}"
            f"{row.p05_2026:>10.2%}"
            f"{row.p95_2026:>10.2%}"
            f"{row.gain_pct_2021_2026:>9.2%}"
        )

    print()
    print(
        f"Leadership changed by 2026: "
        f"{leader_change_count / n_worlds:.2%}"
    )
    print(
        f"BTYT gained weight by 2026: "
        f"{btyt_gain_count / n_worlds:.2%}"
    )
    print(
        f"Average systemic-shock years per world: "
        f"{systemic_year_count / n_worlds:.3f}"
    )
    print(
        f"Average bank-specific shocks per world: "
        f"{bank_shock_count / n_worlds:.3f}"
    )

    return summary


