def generate_foreign_weights(
    banks_df: pd.DataFrame,
    rng: np.random.Generator,
) -> Tuple[Dict[str, float], float]:
    foreign = banks_df.loc[
        (banks_df["bank_scope"] == "FOREIGN")
        & (banks_df["bank_status"] == "ACTIVE")
    ].copy()

    alpha = float(
        rng.uniform(
            FOREIGN_DIRICHLET_ALPHA_LOW,
            FOREIGN_DIRICHLET_ALPHA_HIGH,
        )
    )

    weights = rng.dirichlet(np.full(len(foreign), alpha))

    return dict(zip(foreign["bank_id"], weights)), alpha


def generate_world_affinities(
    banks_df: pd.DataFrame,
    rng: np.random.Generator,
) -> Tuple[Dict[str, Dict[str, float]], float]:
    noise_sd = float(
        rng.uniform(
            AFFINITY_NOISE_SD_LOW,
            AFFINITY_NOISE_SD_HIGH,
        )
    )

    result: Dict[str, Dict[str, float]] = {}

    for row in banks_df.itertuples(index=False):
        if row.bank_scope == "BTYT":
            result[row.bank_id] = {
                "usd_affinity": float(row.usd_affinity),
                "business_affinity": float(row.business_affinity),
                "large_transfer_affinity": float(row.large_transfer_affinity),
            }
            continue

        result[row.bank_id] = {
            "usd_affinity": clip01(
                float(row.usd_affinity) + rng.normal(0.0, noise_sd)
            ),
            "business_affinity": clip01(
                float(row.business_affinity) + rng.normal(0.0, noise_sd)
            ),
            "large_transfer_affinity": clip01(
                float(row.large_transfer_affinity) + rng.normal(0.0, noise_sd)
            ),
        }

    return result, noise_sd


