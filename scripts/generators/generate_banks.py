def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate the BTYT V4.0.1 synthetic banking system."
    )

    parser.add_argument(
        "--world-seed",
        type=int,
        default=WORLD_SEED,
        help=f"Production world seed. Default: {WORLD_SEED}",
    )

    parser.add_argument(
        "--audit-worlds",
        type=int,
        default=0,
        help=(
            "Run the lightweight domestic market audit across N worlds. "
            "Use 10000 for the full design audit."
        ),
    )

    parser.add_argument(
        "--audit-seed",
        type=int,
        default=20260901,
        help="Starting seed used by the cross-world market audit.",
    )

    parser.add_argument(
        "--no-save",
        action="store_true",
        help="Generate and validate without writing production CSV files.",
    )

    return parser.parse_args()


def main() -> None:
    args = parse_args()

    (
        banks_df,
        world_df,
        macro_df,
        market_df,
        financials_df,
    ) = generate_production_world(
        world_seed=args.world_seed,
        save=not args.no_save,
    )

    print_world_summary(
        banks_df=banks_df,
        world_df=world_df,
        macro_df=macro_df,
        market_df=market_df,
        financials_df=financials_df,
        world_seed=args.world_seed,
        saved=not args.no_save,
    )

    if args.audit_worlds > 0:
        audit_df = run_market_audit(
            banks_df=banks_df,
            n_worlds=args.audit_worlds,
            audit_seed=args.audit_seed,
        )

        if not args.no_save:
            AUDIT_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
            audit_df.to_csv(AUDIT_OUTPUT, index=False)
            print(f"\nSaved audit: {AUDIT_OUTPUT}")


if __name__ == "__main__":
    main()
