def calculate_macro_effect(
    bank_id: str,
    macro_row: pd.Series,
) -> float:
    params = MARKET_DYNAMICS[bank_id]

    return float(
        params["growth_beta"] * macro_row["macro_growth_factor"]
        + params["credit_beta"] * macro_row["credit_cycle_factor"]
        + params["usd_beta"] * macro_row["usd_pressure_factor"]
        + params["stress_beta"] * macro_row["financial_stress_factor"]
        + params["digital_beta"] * macro_row["digitalization_factor"]
        + params["cross_border_beta"] * macro_row["cross_border_factor"]
    )


def draw_bank_specific_shock(
    bank_id: str,
    rng: np.random.Generator,
) -> Tuple[float, bool]:
    params = MARKET_DYNAMICS[bank_id]

    # BROU keeps the ordinary shock channel but also receives a very rare,
    # materially larger downside event. This is the only special leadership
    # calibration in V4.0.1 and exists solely to make leadership change
    # possible rather than predetermined.
    if (
        bank_id == "B001"
        and rng.random() < BROU_SEVERE_SHOCK_PROBABILITY
    ):
        magnitude = float(
            rng.uniform(
                BROU_SEVERE_SHOCK_LOW,
                BROU_SEVERE_SHOCK_HIGH,
            )
        )
        return -magnitude, True

    is_shock = bool(rng.random() < params["shock_probability"])

    if not is_shock:
        return 0.0, False

    # Slight negative skew prevents a hidden optimism bias.
    sign = -1.0 if rng.random() < 0.53 else 1.0

    magnitude = float(
        rng.uniform(
            params["shock_scale_low"],
            params["shock_scale_high"],
        )
    )

    return sign * magnitude, True


def build_market_weights_dataframe(
    banks_df: pd.DataFrame,
    world_params_df: pd.DataFrame,
    macro_df: pd.DataFrame,
    world_seed: int,
) -> pd.DataFrame:
    initial_rng = make_stream_rng(world_seed, RNG_STREAM_2021_MARKET)
    dynamics_rng = make_stream_rng(world_seed, RNG_STREAM_MARKET_DYNAMICS)

    current_names = get_bank_lookup(banks_df)

    initial_weights = generate_initial_market_weights(initial_rng)

    center_values = np.array(
        [
            INITIAL_MARKET_SPECS[bank_id]["center"]
            for bank_id in DOMESTIC_SYSTEM_IDS
        ],
        dtype=float,
    )
    center_values /= center_values.sum()

    anchor_share = dict(zip(DOMESTIC_SYSTEM_IDS, center_values))
    anchor_latent = {
        bank_id: float(np.log(anchor_share[bank_id]))
        for bank_id in DOMESTIC_SYSTEM_IDS
    }

    market_params = (
        world_params_df.loc[
            world_params_df["bank_id"].isin(DOMESTIC_SYSTEM_IDS),
            [
                "bank_id",
                "market_persistence",
                "market_innovation_sd",
            ],
        ]
        .set_index("bank_id")
        .to_dict(orient="index")
    )

    rows = []
    previous_latent: Dict[str, float] = {}

    # Persistent strategic state is separate from ordinary AR persistence.
    # A material shock enters this state and then decays over subsequent years.
    strategic_state = {
        bank_id: 0.0
        for bank_id in DOMESTIC_SYSTEM_IDS
    }
    strategic_decay = {
        bank_id: float(
            dynamics_rng.uniform(
                STRATEGIC_SHOCK_DECAY_LOW,
                STRATEGIC_SHOCK_DECAY_HIGH,
            )
        )
        for bank_id in DOMESTIC_SYSTEM_IDS
    }

    # 2021 is generated directly from the bounded initialization contract.
    for bank_id in DOMESTIC_SYSTEM_IDS:
        weight = float(initial_weights[bank_id])
        latent = float(np.log(weight))

        previous_latent[bank_id] = latent

        rows.append(
            {
                "bank_id": bank_id,
                "bank_name": get_temporal_bank_name(
                    bank_id,
                    2021,
                    current_names[bank_id],
                ),
                "year": 2021,
                "market_weight": weight,
                "latent_competitive_state": latent,
                "long_run_anchor": anchor_share[bank_id],
                "persistence": market_params[bank_id]["market_persistence"],
                "macro_effect": 0.0,
                "systemic_shock_effect": 0.0,
                "bank_shock_effect": 0.0,
                "persistent_strategic_effect": 0.0,
                "idiosyncratic_innovation": 0.0,
                "is_bank_shock": False,
                "is_systemic_shock": False,
                "world_seed": int(world_seed),
            }
        )

    for year in YEARS[1:]:
        macro_row = macro_df.loc[macro_df["year"] == year].iloc[0]

        latent_by_bank: Dict[str, float] = {}
        components_by_bank: Dict[str, Dict[str, float | bool]] = {}

        for bank_id in DOMESTIC_SYSTEM_IDS:
            params = MARKET_DYNAMICS[bank_id]

            persistence = float(
                market_params[bank_id]["market_persistence"]
            )
            innovation_sd = float(
                market_params[bank_id]["market_innovation_sd"]
            )

            mu = anchor_latent[bank_id]
            previous = previous_latent[bank_id]

            macro_effect = calculate_macro_effect(bank_id, macro_row)

            systemic_effect = float(
                params["systemic_beta"]
                * macro_row["systemic_shock"]
            )

            bank_shock_effect, is_bank_shock = draw_bank_specific_shock(
                bank_id,
                dynamics_rng,
            )

            strategic_state[bank_id] = (
                strategic_decay[bank_id] * strategic_state[bank_id]
                + bank_shock_effect
            )
            persistent_strategic_effect = float(
                strategic_state[bank_id]
            )

            innovation = float(
                dynamics_rng.normal(0.0, innovation_sd)
            )

            latent = (
                mu
                + persistence * (previous - mu)
                + macro_effect
                + systemic_effect
                + persistent_strategic_effect
                + innovation
            )

            latent = float(
                np.clip(
                    latent,
                    mu - LATENT_DEVIATION_LIMIT,
                    mu + LATENT_DEVIATION_LIMIT,
                )
            )

            latent_by_bank[bank_id] = latent

            components_by_bank[bank_id] = {
                "macro_effect": macro_effect,
                "systemic_shock_effect": systemic_effect,
                "bank_shock_effect": bank_shock_effect,
                "persistent_strategic_effect": persistent_strategic_effect,
                "idiosyncratic_innovation": innovation,
                "is_bank_shock": is_bank_shock,
            }

        latent_vector = np.array(
            [latent_by_bank[bank_id] for bank_id in DOMESTIC_SYSTEM_IDS],
            dtype=float,
        )

        weights = softmax(latent_vector)
        weight_by_bank = dict(zip(DOMESTIC_SYSTEM_IDS, weights))

        for bank_id in DOMESTIC_SYSTEM_IDS:
            components = components_by_bank[bank_id]

            rows.append(
                {
                    "bank_id": bank_id,
                    "bank_name": get_temporal_bank_name(
                        bank_id,
                        year,
                        current_names[bank_id],
                    ),
                    "year": int(year),
                    "market_weight": float(weight_by_bank[bank_id]),
                    "latent_competitive_state": latent_by_bank[bank_id],
                    "long_run_anchor": anchor_share[bank_id],
                    "persistence": market_params[bank_id]["market_persistence"],
                    "macro_effect": components["macro_effect"],
                    "systemic_shock_effect": components[
                        "systemic_shock_effect"
                    ],
                    "bank_shock_effect": components["bank_shock_effect"],
                    "persistent_strategic_effect": components[
                        "persistent_strategic_effect"
                    ],
                    "idiosyncratic_innovation": components[
                        "idiosyncratic_innovation"
                    ],
                    "is_bank_shock": components["is_bank_shock"],
                    "is_systemic_shock": bool(
                        macro_row["systemic_shock_flag"]
                    ),
                    "world_seed": int(world_seed),
                }
            )

        previous_latent = latent_by_bank

    return pd.DataFrame(rows)


