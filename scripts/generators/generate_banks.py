def generate_initial_market_weights(
    rng: np.random.Generator,
) -> Dict[str, float]:
    """
    Generate the 2021 domestic-system vector inside the explicit plausibility
    bands.

    BROU is required to be the largest institution in 2021. This anchors the
    historical starting hierarchy while preserving stochastic values for every
    bank.
    """
    ids = list(DOMESTIC_SYSTEM_IDS)

    lower = np.array(
        [INITIAL_MARKET_SPECS[bank_id]["low"] for bank_id in ids],
        dtype=float,
    )
    center = np.array(
        [INITIAL_MARKET_SPECS[bank_id]["center"] for bank_id in ids],
        dtype=float,
    )
    upper = np.array(
        [INITIAL_MARKET_SPECS[bank_id]["high"] for bank_id in ids],
        dtype=float,
    )

    if lower.sum() > 1.0 or upper.sum() < 1.0:
        raise ValueError("The 2021 market bands do not define a feasible simplex.")

    # Center the preference on the desired interior location above lower bounds.
    preferred_residual = np.clip(center - lower, 1e-8, None)
    preferred_residual /= preferred_residual.sum()

    for _ in range(INITIAL_MAX_ATTEMPTS):
        alpha = float(
            rng.uniform(
                INITIAL_DIRICHLET_ALPHA_LOW,
                INITIAL_DIRICHLET_ALPHA_HIGH,
            )
        )

        concentration = np.maximum(
            preferred_residual * alpha * len(ids),
            0.35,
        )

        preferences = rng.dirichlet(concentration)

        center_noise = rng.normal(
            0.0,
            INITIAL_CENTER_NOISE_SD,
            size=len(ids),
        )

        preferences = np.clip(preferences + center_noise, 1e-8, None)
        preferences /= preferences.sum()

        weights = allocate_bounded_residual(
            lower=lower,
            upper=upper,
            preferences=preferences,
            target_sum=1.0,
        )

        result = dict(zip(ids, weights))

        brou_weight = result["B001"]
        largest_other = max(
            value
            for bank_id, value in result.items()
            if bank_id != "B001"
        )

        if brou_weight > largest_other:
            return result

    raise RuntimeError(
        "Unable to generate a valid 2021 market state with BROU as leader."
    )


